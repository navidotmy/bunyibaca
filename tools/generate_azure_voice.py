#!/usr/bin/env python3
"""BunyiBaca native Malay neural voice audition pack (Microsoft Azure Speech).

Safety: defaults to no network calls, no billing, and outputs to voice-review/ only.
No assets are promoted into the children's public PWA automatically.

Usage:
    python3 tools/generate_azure_voice.py --dry-run
    AZURE_SPEECH_KEY=... AZURE_SPEECH_REGION=southeastasia \
      python3 tools/generate_azure_voice.py --confirm-billing --limit 16
    AZURE_SPEECH_KEY=... AZURE_SPEECH_REGION=southeastasia \
      python3 tools/generate_azure_voice.py --confirm-billing --voice ms-MY-OsmanNeural --limit 16

The Azure Speech resource must be configured using a commercial-use-eligible tier
before its generated output is shipped commercially. Azure commercial rights and
phonetic accuracy must be checked before distributing recordings.
"""
from __future__ import annotations

import argparse
import csv
import html
import json
import os
import re
import subprocess
import sys
import time
import unicodedata
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VOICES = ('ms-MY-YasminNeural', 'ms-MY-OsmanNeural')
# Carefully selected audition words testing important Malay contrasts.
# This is a pronunciation *screening* list, not an approved phonemic dictionary.
PILOT = [
    ('segment','ba'), ('segment','bi'), ('segment','bu'),
    ('segment','ma'), ('segment','mi'), ('segment','mu'),
    ('word','baca'), ('word','baju'), ('word','susu'),
    ('word','mata'), ('word','makan'), ('word','emak'),
    ('word','ekor'), ('word','bunga'), ('word','nyanyi'),
    ('word','khabar'), ('word','syarat'), ('word','ibu'),
]


def filename(text: str) -> str:
    """Mirror the existing BunyiBaca speech.mjs asset naming convention."""
    text = unicodedata.normalize('NFC', text.lower())
    safe = ''.join(ch if ch.isalnum() else '_' for ch in text)
    if len(safe) <= 80:
        return safe
    # FNV-1a over JavaScript UTF-16 code units to match speech.mjs.
    h = 2166136261
    for ch in text:
        cp = ord(ch)
        units = [cp] if cp <= 0xFFFF else [0xD800 + ((cp-0x10000)>>10), 0xDC00 + ((cp-0x10000)&0x3FF)]
        for unit in units:
            h = ((h ^ unit) * 16777619) & 0xffffffff
    return safe[:48] + '_' + format(h, 'x')


def load_entries(full: bool):
    raw = subprocess.check_output(['node', 'tools/build_audio_catalog.mjs'], cwd=ROOT)
    items = json.loads(raw)
    by_key = {(e['kind'], e['text']): e for e in items}
    if not full:
        return [by_key[p] for p in PILOT if p in by_key]
    # Do not synthesize consonant-only letter labels or isolated digraph phonemes:
    # a neural voice may substitute letter names, creating incorrect teaching.
    excluded = set('bcdfghjklmnpqrstvwxyz') | {'ng','ny','sy','kh','gh'}
    return [e for e in items if not (e['kind'] == 'segment' and e['text'].casefold() in excluded)]


def speech_markup(text: str, voice: str, kind: str, ipa: str | None):
    rate = '-17%' if kind == 'segment' else ('-9%' if kind == 'word' else '-4%')
    child = html.escape(text, quote=False)
    if ipa:
        # IPA is optional and deliberately reviewed externally, not generated by guessing.
        child = f'<phoneme alphabet="ipa" ph="{html.escape(ipa,quote=True)}">{child}</phoneme>'
    return (
        '<speak version="1.0" xmlns="http://www.w3.org/2001/10/synthesis" '
        'xml:lang="ms-MY">'
        f'<voice name="{voice}"><prosody rate="{rate}">{child}</prosody></voice>'
        '</speak>'
    )


def request_audio(ssml: str, key: str, region: str) -> bytes:
    url = f'https://{region}.tts.speech.microsoft.com/cognitiveservices/v1'
    req = urllib.request.Request(url, data=ssml.encode('utf-8'), method='POST', headers={
        'Ocp-Apim-Subscription-Key': key,
        'Content-Type': 'application/ssml+xml; charset=utf-8',
        'X-Microsoft-OutputFormat': 'audio-24khz-48kbitrate-mono-mp3',
        'User-Agent': 'BunyiBaca-Phonics-QA/1.0',
    })
    for attempt in range(5):
        try:
            with urllib.request.urlopen(req, timeout=90) as response:
                audio = response.read()
                if len(audio) < 500:
                    raise RuntimeError('Received suspiciously short audio (not accepted).')
                return audio
        except urllib.error.HTTPError as exc:
            body = exc.read(400).decode('utf-8', 'replace')
            if exc.code in (429, 500, 502, 503, 504) and attempt < 4:
                time.sleep(min(20, 2 ** attempt))
                continue
            raise RuntimeError(f'Azure returned HTTP {exc.code}: {body}') from exc
    raise RuntimeError('Unable to synthesise after retries')


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--voice', choices=VOICES, default=VOICES[0])
    parser.add_argument('--all', action='store_true', help='All eligible catalog items, rather than the 18-item audition list')
    parser.add_argument('--limit', type=int, default=16, help='Maximum number of clips to generate (positive)')
    parser.add_argument('--dry-run', action='store_true', help='Plan only, never use an API key')
    parser.add_argument('--confirm-billing', action='store_true', help='Explicit approval for potentially billed Azure TTS requests')
    parser.add_argument('--out', default='voice-review', help='Private QA output folder, never the public app assets')
    parser.add_argument('--pronunciations', help='Optional JSON dict: exact text -> reviewed IPA; no automatic phoneme guessing')
    args = parser.parse_args()
    if not 1 <= args.limit <= 1000:
        parser.error('--limit must be between 1 and 1000')
    entries = load_entries(args.all)[:args.limit]
    if not entries:
        parser.error('No audio entries selected')
    overrides = {}
    if args.pronunciations:
        overrides = json.loads(Path(args.pronunciations).read_text(encoding='utf-8'))
        if not isinstance(overrides, dict) or not all(isinstance(k,str) and isinstance(v,str) for k,v in overrides.items()):
            parser.error('Pronunciation overrides must be a JSON object mapping text to reviewed IPA strings')
    print(f'VOICE={args.voice}; CLIPS={len(entries)}; TOTAL_TEXT_CHARACTERS={sum(len(x["text"]) for x in entries)}')
    for e in entries:
        print(f'  {e["kind"]:8} {e["text"][:70]}')
    if args.dry_run or not args.confirm_billing:
        print('DRY RUN: no audio generated and no API calls made. Pass --confirm-billing to generate.')
        return 0
    key = os.environ.get('AZURE_SPEECH_KEY')
    region = os.environ.get('AZURE_SPEECH_REGION')
    if not key or not region:
        parser.error('Set AZURE_SPEECH_KEY and AZURE_SPEECH_REGION in private environment/GitHub secrets')
    if not re.fullmatch(r'[a-z][a-z0-9-]{1,35}', region):
        parser.error('Invalid Azure region identifier')
    out = (ROOT / args.out).resolve()
    # Never overwrite bundled unreviewed placeholders without separate editorial approval.
    if out == (ROOT/'assets'/'audio').resolve() or (ROOT/'assets'/'audio').resolve() in out.parents:
        parser.error('Output may not be within public assets/audio; use a separate QA folder')
    rows = []
    for i, e in enumerate(entries, 1):
        text,kind=e['text'],e['kind']
        relative=f'{kind}/{filename(text)}.mp3'
        dest=out/args.voice/relative
        dest.parent.mkdir(parents=True,exist_ok=True)
        ssml=speech_markup(text,args.voice,kind,overrides.get(text))
        try:
            if not dest.exists():
                dest.write_bytes(request_audio(ssml,key,region))
                time.sleep(.4)
            status='NEEDS_NATIVE_SPEAKER_REVIEW'
            rows.append({'number':i,'voice':args.voice,'kind':kind,'text':text,'path':str(dest.relative_to(out)),'status':status,'phoneme_override':overrides.get(text,''),'notes':''})
            print(f'[{i}/{len(entries)}] Wrote {dest.name} ({len(dest.read_bytes())} bytes)')
        except Exception as exc:
            print(f'Audio generation failed at item {i}: {exc}', file=sys.stderr)
            break
    out.mkdir(parents=True,exist_ok=True)
    with (out / f'qa-{args.voice}.csv').open('w', newline='',encoding='utf-8-sig') as f:
        writer=csv.DictWriter(f,fieldnames=['number','voice','kind','text','path','status','phoneme_override','notes'])
        writer.writeheader();writer.writerows(rows)
    (out / f'qa-{args.voice}.json').write_text(json.dumps(rows,ensure_ascii=False,indent=2),encoding='utf-8')
    print(f'QA manifest: {out / f"qa-{args.voice}.csv"}')
    print('Do not deploy without a Malay-language phonics specialist approving every clip.')
    return 0 if len(rows)==len(entries) else 1

if __name__=='__main__':
    raise SystemExit(main())